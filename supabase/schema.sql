create or replace function cf.period(d jsonb, out p_start date, out p_end date, out p_label text) language plpgsql stable as $$
declare t date := cf.today(); preset text := coalesce(d ->> 'preset', 'Este mês');
begin
  case preset
    when 'Hoje' then p_start := t; p_end := t;
    when 'Esta semana' then p_start := t - (extract(isodow from t)::int - 1); p_end := p_start + 6;
    when 'Mês anterior' then p_start := date_trunc('month', t - interval '1 month')::date;
                             p_end := (date_trunc('month', t) - interval '1 day')::date;
    when 'Este ano' then p_start := make_date(extract(year from t)::int, 1, 1); p_end := make_date(extract(year from t)::int, 12, 31);
    when 'Ano anterior' then p_start := make_date(extract(year from t)::int - 1, 1, 1);
                             p_end := make_date(extract(year from t)::int - 1, 12, 31);
    when 'Todo o período' then p_start := '0001-01-01'; p_end := '9999-12-31';
    when 'Período personalizado' then p_start := coalesce(cf.dt(d, 'start'), t); p_end := coalesce(cf.dt(d, 'end'), t);
    else preset := 'Este mês'; p_start := date_trunc('month', t)::date;
         p_end := (date_trunc('month', t) + interval '1 month - 1 day')::date;
  end case;
  p_label := preset;
end $$;

create or replace function cf.dashboard(d jsonb) returns jsonb language plpgsql stable as $$
declare p record; v_rev bigint; v_cost bigint; v_prof bigint; v_upf bigint; v_paid bigint; arec bigint; venc bigint;
        nb bigint; ns bigint; monthly jsonb; modules jsonb; acts jsonb; m_start date;
begin
  select * into p from cf.period(d);
  with revs as (
    select date, 'fornada' module, revenue, total_cost cost, profit, paid_upfront from cf.batches where status = 'ativo'
    union all
    select date, kind, amount, costs + extra_expenses, profit, paid_upfront from cf.services where status = 'ativo')
  select coalesce(sum(revenue), 0), coalesce(sum(cost), 0), coalesce(sum(profit), 0), coalesce(sum(paid_upfront), 0)
    into v_rev, v_cost, v_prof, v_upf from revs where date between p.p_start and p.p_end;
  select coalesce(sum(pm.amount), 0) into v_paid from cf.payments pm join cf.receivables r on r.id = pm.receivable_id
   where pm.status = 'ativo' and r.status = 'aberto' and pm.date between p.p_start and p.p_end;
  select coalesce(sum(greatest(r.amount - r.paid, 0)), 0),
         coalesce(sum(case when r.due_date < cf.today() then greatest(r.amount - r.paid, 0) else 0 end), 0)
    into arec, venc from cf.v_receivables r
   where r.status = 'aberto' and r.amount > r.paid and r.issue_date between p.p_start and p.p_end;
  select count(*) into nb from cf.batches where status = 'ativo' and date between p.p_start and p.p_end;
  select count(*) into ns from cf.services where status = 'ativo' and date between p.p_start and p.p_end;
  -- últimos 12 meses do período (ou até hoje)
  m_start := date_trunc('month', least(p.p_end, cf.today()))::date - interval '11 months';
  if p.p_start > m_start then m_start := date_trunc('month', p.p_start)::date; end if;
  with revs as (
    select date, revenue, profit from cf.batches where status = 'ativo'
    union all select date, amount, profit from cf.services where status = 'ativo'),
  months as (select generate_series(m_start, least(p.p_end, cf.today()), interval '1 month')::date m)
  select coalesce(jsonb_agg(jsonb_build_object(
           'mes', to_char(m, 'YYYY-MM'),
           'rotulo', (array['jan','fev','mar','abr','mai','jun','jul','ago','set','out','nov','dez'])[extract(month from m)::int]
                     || '/' || extract(year from m)::int,
           'faturamento', coalesce((select sum(revenue) from revs where date_trunc('month', date) = m and date between p.p_start and p.p_end), 0),
           'lucro', coalesce((select sum(profit) from revs where date_trunc('month', date) = m and date between p.p_start and p.p_end), 0))
         order by m), '[]') into monthly from months;
  with revs as (
    select date, 'fornada' module, revenue, profit from cf.batches where status = 'ativo'
    union all select date, kind, amount, profit from cf.services where status = 'ativo')
  select jsonb_agg(jsonb_build_object('modulo', k, 'rotulo', l,
           'faturamento', coalesce((select sum(revenue) from revs where module = k and date between p.p_start and p.p_end), 0),
           'lucro', coalesce((select sum(profit) from revs where module = k and date between p.p_start and p.p_end), 0),
           'registros', (select count(*) from revs where module = k and date between p.p_start and p.p_end)) order by o)
    into modules from (values (1, 'fornada', 'Salgados'), (2, 'limpeza', 'Limpeza'), (3, 'outro', 'Outros serviços')) v(o, k, l);
  select coalesce(jsonb_agg(jsonb_build_object('ts', ts, 'entity', entity, 'entity_id', entity_id,
           'type', case entity when 'fornada' then 'Fornada' when 'limpeza' then 'Limpeza' when 'outro' then 'Outro serviço'
                               when 'receber' then 'A receber' when 'pagamento' then 'Pagamento' when 'categoria' then 'Categoria'
                               when 'configuracao' then 'Configurações' else 'Sistema' end,
           'action', case action when 'criar' then 'Novo registro' when 'editar' then 'Correção' when 'cancelar' then 'Cancelamento'
                                 when 'estornar' then 'Estorno' else initcap(action) end,
           'summary', summary) order by id desc), '[]')
    into acts from (select * from cf.audit_log order by id desc limit 25) a;
  return jsonb_build_object(
    'period', jsonb_build_object('label', p.p_label),
    'kpis', jsonb_build_object('faturamento', v_rev, 'custos', v_cost, 'lucro', v_prof, 'recebido', v_upf + v_paid,
                               'a_receber', arec, 'vencido', venc, 'fornadas', nb, 'servicos', ns, 'margem', cf.pct(v_prof, v_rev)),
    'monthly', monthly, 'modules', modules, 'activity', acts);
end $$;

create or replace function cf.list_batches(d jsonb) returns jsonb language plpgsql stable as $$
declare p record; items jsonb;
begin
  select * into p from cf.period(d);
  select coalesce(jsonb_agg(cf.batch_json(b) order by b.date desc, b.id desc), '[]') into items
    from cf.batches b where b.date between p.p_start and p.p_end;
  return jsonb_build_object('items', items, 'summary', (
    select jsonb_build_object(
      'fornadas', count(*), 'produzido', coalesce(sum((i ->> 'qty_produced')::bigint), 0),
      'vendido', coalesce(sum((i ->> 'qty_sold')::bigint), 0), 'nao_vendido', coalesce(sum((i ->> 'qty_unsold')::bigint), 0),
      'faturamento', coalesce(sum((i ->> 'revenue')::bigint), 0), 'custos', coalesce(sum((i ->> 'total_cost')::bigint), 0),
      'lucro', coalesce(sum((i ->> 'profit')::bigint), 0), 'recebido', coalesce(sum((i ->> 'received')::bigint), 0),
      'a_receber', coalesce(sum((i ->> 'to_receive')::bigint), 0),
      'margem', cf.pct(coalesce(sum((i ->> 'profit')::bigint), 0), coalesce(sum((i ->> 'revenue')::bigint), 0)))
      from jsonb_array_elements(items) i where i ->> 'status' = 'ativo'));
end $$;

create or replace function cf.list_jobs(d jsonb) returns jsonb language plpgsql stable as $$
declare p record; items jsonb; k text := coalesce(d ->> 'kind', 'limpeza'); summ jsonb; cats jsonb;
begin
  select * into p from cf.period(d);
  select coalesce(jsonb_agg(cf.job_json(s) order by s.date desc, s.id desc), '[]') into items
    from cf.services s where s.kind = k and s.date between p.p_start and p.p_end;
  select jsonb_build_object(
      'servicos', count(*), 'faturamento', coalesce(sum((i ->> 'amount')::bigint), 0),
      'custos', coalesce(sum((i ->> 'total_cost')::bigint), 0), 'lucro', coalesce(sum((i ->> 'profit')::bigint), 0),
      'recebido', coalesce(sum((i ->> 'received')::bigint), 0), 'a_receber', coalesce(sum((i ->> 'to_receive')::bigint), 0),
      'pagos', count(*) filter (where (i ->> 'to_receive')::bigint = 0),
      'pendentes', count(*) filter (where (i ->> 'to_receive')::bigint > 0),
      'media', case when count(*) = 0 then 0 else coalesce(sum((i ->> 'amount')::bigint), 0) / count(*) end,
      'margem', cf.pct(coalesce(sum((i ->> 'profit')::bigint), 0), coalesce(sum((i ->> 'amount')::bigint), 0)))
    into summ from jsonb_array_elements(items) i where i ->> 'status' = 'ativo';
  select coalesce(jsonb_agg(c order by (c ->> 'faturamento')::bigint desc), '[]') into cats from (
    select jsonb_build_object('categoria', coalesce(i ->> 'category_name', 'Sem categoria'), 'qtd', count(*),
             'faturamento', sum((i ->> 'amount')::bigint), 'custos', sum((i ->> 'total_cost')::bigint),
             'lucro', sum((i ->> 'profit')::bigint), 'a_receber', sum((i ->> 'to_receive')::bigint)) c
      from jsonb_array_elements(items) i where i ->> 'status' = 'ativo'
     group by coalesce(i ->> 'category_name', 'Sem categoria')) x;
  return jsonb_build_object('items', items, 'summary', summ, 'by_category', cats);
end $$;

create or replace function cf.list_receivables() returns jsonb language plpgsql stable as $$
declare items jsonb;
begin
  select coalesce(jsonb_agg(cf.rec_json(r) order by r.issue_date desc, r.id desc), '[]') into items from cf.v_receivables r;
  return jsonb_build_object('items', items, 'totals', (
    select jsonb_build_object(
      'em_aberto', coalesce(sum((i ->> 'balance')::bigint) filter (where i ->> 'status' in ('Pendente', 'Parcialmente pago', 'Vencido')), 0),
      'qtd_aberto', count(*) filter (where i ->> 'status' in ('Pendente', 'Parcialmente pago', 'Vencido')),
      'vencido', coalesce(sum((i ->> 'balance')::bigint) filter (where i ->> 'status' = 'Vencido'), 0),
      'qtd_vencido', count(*) filter (where i ->> 'status' = 'Vencido'),
      'pendente', coalesce(sum((i ->> 'balance')::bigint) filter (where i ->> 'status' = 'Pendente'), 0),
      'parcial_saldo', coalesce(sum((i ->> 'balance')::bigint) filter (where i ->> 'status' = 'Parcialmente pago'), 0),
      'recebido', coalesce(sum((i ->> 'paid')::bigint) filter (where i ->> 'status' <> 'Cancelado'), 0))
    from jsonb_array_elements(items) i));
end $$;

-- ------------------------------------------------------------------ sincronização (PC)
-- tudo o que mudou depois de "since" (o PC guarda uma cópia local para funcionar sem internet)
create or replace function cf.dump(p_since bigint) returns jsonb language sql stable as $$
  select jsonb_build_object(
    'rev', (select last_value from cf.rev_seq),
    'settings', (select coalesce(jsonb_agg(to_jsonb(t) - 'rev' order by rev), '[]') from cf.settings t where rev > p_since),
    'clients', (select coalesce(jsonb_agg(to_jsonb(t) - 'rev' order by rev), '[]') from cf.clients t where rev > p_since),
    'categories', (select coalesce(jsonb_agg(to_jsonb(t) - 'rev' order by rev), '[]') from cf.categories t where rev > p_since),
    'batches', (select coalesce(jsonb_agg(to_jsonb(t) - 'rev' order by rev), '[]') from cf.batches t where rev > p_since),
    'services', (select coalesce(jsonb_agg(to_jsonb(t) - 'rev' order by rev), '[]') from cf.services t where rev > p_since),
    'receivables', (select coalesce(jsonb_agg(to_jsonb(t) - 'rev' order by rev), '[]') from cf.receivables t where rev > p_since),
    'payments', (select coalesce(jsonb_agg(to_jsonb(t) - 'rev' order by rev), '[]') from cf.payments t where rev > p_since),
    'audit_log', (select coalesce(jsonb_agg(to_jsonb(t) - 'rev' order by rev), '[]') from cf.audit_log t where rev > p_since))
$$;

-- carga completa (migração dos dados do PC ou restauração de backup); preserva os identificadores
create or replace function cf.import_all(d jsonb, p_replace boolean) returns jsonb language plpgsql as $$
declare t text; cols text; flt text;
begin
  if not p_replace and (exists (select 1 from cf.batches) or exists (select 1 from cf.services)
                        or exists (select 1 from cf.receivables)) then
    perform cf.fail('A nuvem já tem dados. Use a restauração para substituí-los.');
  end if;
  -- (o Supabase bloqueia DELETE/UPDATE sem WHERE vindos da API; por isso o "where id is not null")
  delete from cf.payments where id is not null; delete from cf.receivables where id is not null;
  delete from cf.batches where id is not null; delete from cf.services where id is not null;
  delete from cf.audit_log where id is not null; delete from cf.categories where id is not null;
  delete from cf.clients where id is not null;
  delete from cf.settings where key in ('app_display_name', 'salgado_price', 'salgado_margin', 'salgado_cost', 'limpeza_default_cost');
  foreach t in array array['clients','categories','batches','services','receivables','payments','audit_log','settings'] loop
    select string_agg(quote_ident(column_name), ', ' order by ordinal_position) into cols
      from information_schema.columns where table_schema = 'cf' and table_name = t and column_name <> 'rev';
    flt := case when t = 'settings'
                then $f$ where key in ('app_display_name', 'salgado_price', 'salgado_margin', 'salgado_cost', 'limpeza_default_cost')$f$
                else '' end;
    execute format('insert into cf.%1$I (%2$s) select %2$s from jsonb_populate_recordset(null::cf.%1$I, $1)', t, cols) || flt
      using coalesce(d -> t, '[]'::jsonb);
  end loop;
  -- novos registros continuam a numeração depois dos importados
  foreach t in array array['clients','categories','batches','services','receivables','payments','audit_log'] loop
    execute format('select setval(pg_get_serial_sequence(''cf.%1$s'', ''id''), greatest((select coalesce(max(id), 0) from cf.%1$I), 1), (select count(*) > 0 from cf.%1$I))', t);
  end loop;
  -- marca tudo como alterado para os aparelhos baixarem de novo
  foreach t in array array['settings','clients','categories','batches','services','receivables','payments','audit_log'] loop
    execute format('update cf.%I set rev = nextval(''cf.rev_seq'') where rev is not null', t);
  end loop;
  update cf.secrets set epoch = cf.now_txt() || '-' || substr(md5(random()::text), 1, 6) where id = 1;
  perform cf.audit('sistema', null, 'sistema', case when p_replace then 'Dados da nuvem substituídos por um backup'
                                                    else 'Dados do PC enviados para a nuvem' end);
  return jsonb_build_object('ok', true, 'reset', true);
end $$;

create or replace function cf.default_categories() returns void language plpgsql as $$
declare n text;
begin
  if not exists (select 1 from cf.categories) then
    foreach n in array array['Manutenção', 'Pequenos trabalhos', 'Vendas avulsas', 'Outros'] loop
      insert into cf.categories (name, name_key, active, created_at) values (n, cf.name_key(n), 1, cf.now_txt());
    end loop;
  end if;
end $$;

-- ------------------------------------------------------------------ ponto de entrada único
create or replace function public.cf_api(p_key text, p_action text, p_data jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path = cf, public, extensions as $$
declare h text; d jsonb := coalesce(p_data, '{}'::jsonb); v_id bigint := nullif(d ->> 'id', '')::bigint; stored text;
begin
  if p_key is null or length(p_key) < 20 then perform cf.fail('Acesso não autorizado.'); end if;
  h := encode(extensions.digest(p_key, 'sha256'), 'hex');
  select key_hash into stored from cf.secrets s where s.id = 1;
  if p_action = 'claim' then
    -- o primeiro aparelho (o PC) registra a chave secreta; depois disso, nenhuma outra é aceita
    if stored is null then
      insert into cf.secrets (id, key_hash) values (1, h);
      perform cf.default_categories();
      return jsonb_build_object('ok', true, 'claimed', true);
    end if;
    if stored <> h then perform cf.fail('Acesso não autorizado.'); end if;
    return jsonb_build_object('ok', true, 'claimed', false);
  end if;
  if stored is null or stored <> h then perform cf.fail('Acesso não autorizado.'); end if;

  case p_action
    when 'ping' then return jsonb_build_object('rev', (select last_value from cf.rev_seq), 'today', cf.today(),
                                               'epoch', (select epoch from cf.secrets where secrets.id = 1));
    when 'meta' then
      return jsonb_build_object(
        'app_name', cf.setting('app_display_name', 'Controle Financeiro'),
        'price', cf.setting('salgado_price', '500')::bigint, 'cost', cf.setting('salgado_cost', '250')::bigint,
        'cleaning_cost', cf.setting('limpeza_default_cost', '0')::bigint,
        'categories', (select coalesce(jsonb_agg(jsonb_build_object('id', c.id, 'name', c.name) order by lower(c.name)), '[]')
                         from cf.categories c where active = 1),
        'clients', (select coalesce(jsonb_agg(name order by lower(name)), '[]') from cf.clients),
        'methods', '["Dinheiro","Transferência","Cartão de débito","Cartão de crédito","Outro"]'::jsonb,
        'rev', (select last_value from cf.rev_seq), 'today', cf.today());
    when 'dashboard' then return cf.dashboard(d);
    when 'batches' then return cf.list_batches(d);
    when 'jobs' then return cf.list_jobs(d);
    when 'receivables' then return cf.list_receivables();
    when 'batch' then return (select cf.batch_json(b) from cf.batches b where b.id = v_id);
    when 'job' then return (select cf.job_json(s) from cf.services s where s.id = v_id);
    when 'receivable' then
      return (select cf.rec_json(r) || jsonb_build_object('payments',
                (select coalesce(jsonb_agg(to_jsonb(p) - 'rev' order by p.date, p.id), '[]') from cf.payments p where p.receivable_id = r.id))
                from cf.v_receivables r where r.id = v_id);
    when 'batch_create' then return jsonb_build_object('id', cf.batch_save(null, d));
    when 'batch_update' then return jsonb_build_object('id', cf.batch_save(v_id, d));
    when 'batch_cancel' then perform cf.batch_cancel(v_id, d ->> 'reason');
    when 'job_create' then return jsonb_build_object('id', cf.job_save(null, d));
    when 'job_update' then return jsonb_build_object('id', cf.job_save(v_id, d));
    when 'job_cancel' then perform cf.job_cancel(v_id, d ->> 'reason');
    when 'rec_create' then return jsonb_build_object('id', cf.rec_create(d));
    when 'rec_update' then perform cf.rec_update(v_id, d);
    when 'rec_cancel' then perform cf.rec_cancel(v_id, d ->> 'reason');
    when 'pay_add' then return jsonb_build_object('id', cf.pay_add(v_id, d));
    when 'pay_reverse' then perform cf.pay_reverse(v_id, d ->> 'reason');
    when 'category_save' then return jsonb_build_object('id', cf.cat_save(d));
    when 'settings_save' then perform cf.settings_save(d);
    when 'dump' then return cf.dump(coalesce((d ->> 'since')::bigint, 0))
                            || jsonb_build_object('epoch', (select epoch from cf.secrets where secrets.id = 1));
    when 'import' then return cf.import_all(d -> 'data', coalesce((d ->> 'replace')::boolean, false));
    else perform cf.fail('Ação desconhecida: ' || p_action);
  end case;
  return jsonb_build_object('ok', true);
end $$;

revoke all on function public.cf_api(text, text, jsonb) from public;
grant execute on function public.cf_api(text, text, jsonb) to anon, authenticated, service_role;
