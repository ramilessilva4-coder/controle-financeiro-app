-- =====================================================================================
-- Controle Financeiro — banco na nuvem (Supabase / PostgreSQL)
--
-- * As tabelas ficam no schema privado "cf" (não exposto pela API do Supabase).
-- * Toda leitura e gravação passa por UMA função pública: public.cf_api(chave, ação, dados).
--   Ela confere a chave secreta do aparelho e executa as mesmas regras do programa do PC.
-- * O papel "anon" só pode executar cf_api; não enxerga nenhuma tabela.
-- * Script idempotente: pode ser executado de novo sem perder dados.
-- =====================================================================================

create schema if not exists extensions;
create extension if not exists unaccent with schema extensions;
create extension if not exists pgcrypto with schema extensions;

create schema if not exists cf;
revoke all on schema cf from public;

create sequence if not exists cf.rev_seq;

-- ------------------------------------------------------------------ tabelas
create table if not exists cf.secrets (
  id         int primary key default 1 check (id = 1),
  key_hash   text not null,
  created_at timestamptz not null default now()
);
-- "epoch" muda quando os dados são substituídos por inteiro (migração/restauração): os aparelhos recarregam tudo
alter table cf.secrets add column if not exists epoch text not null default '';

create table if not exists cf.settings (
  key        text primary key,
  value      text not null,
  updated_at text not null,
  rev        bigint not null default nextval('cf.rev_seq')
);

create table if not exists cf.clients (
  id         bigint generated by default as identity primary key,
  name       text not null,
  name_key   text not null unique,
  contact    text,
  created_at text not null,
  rev        bigint not null default nextval('cf.rev_seq')
);

create table if not exists cf.categories (
  id         bigint generated by default as identity primary key,
  name       text not null,
  name_key   text not null unique,
  active     int not null default 1 check (active in (0, 1)),
  created_at text not null,
  rev        bigint not null default nextval('cf.rev_seq')
);

create table if not exists cf.batches (
  id             bigint generated by default as identity primary key,
  date           date not null,
  qty_produced   bigint not null check (qty_produced > 0),
  qty_sold       bigint not null check (qty_sold >= 0 and qty_sold <= qty_produced),
  unit_price     bigint not null check (unit_price >= 0),
  unit_cost      bigint not null check (unit_cost >= 0),
  extra_expenses bigint not null default 0 check (extra_expenses >= 0),
  revenue        bigint not null check (revenue >= 0),
  total_cost     bigint not null check (total_cost >= 0),
  profit         bigint not null,
  paid_upfront   bigint not null default 0 check (paid_upfront >= 0 and paid_upfront <= revenue),
  payment_method text,
  client_id      bigint references cf.clients(id),
  notes          text,
  status         text not null default 'ativo' check (status in ('ativo', 'cancelado')),
  cancel_reason  text,
  created_at     text not null,
  updated_at     text not null,
  cancelled_at   text,
  rev            bigint not null default nextval('cf.rev_seq')
);
create index if not exists ix_batches_date on cf.batches(date);

create table if not exists cf.services (
  id               bigint generated by default as identity primary key,
  kind             text not null check (kind in ('limpeza', 'outro')),
  date             date not null,
  title            text not null,
  description      text,
  client_id        bigint references cf.clients(id),
  address          text,
  category_id      bigint references cf.categories(id),
  amount           bigint not null check (amount >= 0),
  costs            bigint not null default 0 check (costs >= 0),
  extra_expenses   bigint not null default 0 check (extra_expenses >= 0),
  cost_description text,
  profit           bigint not null,
  paid_upfront     bigint not null default 0 check (paid_upfront >= 0 and paid_upfront <= amount),
  payment_method   text,
  notes            text,
  status           text not null default 'ativo' check (status in ('ativo', 'cancelado')),
  cancel_reason    text,
  created_at       text not null,
  updated_at       text not null,
  cancelled_at     text,
  rev              bigint not null default nextval('cf.rev_seq')
);
create index if not exists ix_services_kind_date on cf.services(kind, date);

create table if not exists cf.receivables (
  id            bigint generated by default as identity primary key,
  client_id     bigint not null references cf.clients(id),
  description   text not null,
  amount        bigint not null check (amount > 0),
  issue_date    date not null,
  due_date      date,
  contact       text,
  origin_type   text not null check (origin_type in ('fornada', 'limpeza', 'outro', 'manual')),
  origin_id     bigint,
  notes         text,
  status        text not null default 'aberto' check (status in ('aberto', 'cancelado')),
  cancel_reason text,
  created_at    text not null,
  updated_at    text not null,
  cancelled_at  text,
  rev           bigint not null default nextval('cf.rev_seq'),
  check ((origin_type = 'manual' and origin_id is null) or (origin_type <> 'manual' and origin_id is not null))
);
-- impede duas dívidas ativas para o mesmo registro de origem
create unique index if not exists ux_receivables_origin on cf.receivables(origin_type, origin_id)
  where origin_id is not null and status = 'aberto';

create table if not exists cf.payments (
  id             bigint generated by default as identity primary key,
  receivable_id  bigint not null references cf.receivables(id),
  amount         bigint not null check (amount > 0),
  date           date not null,
  method         text,
  notes          text,
  status         text not null default 'ativo' check (status in ('ativo', 'estornado')),
  reverse_reason text,
  created_at     text not null,
  reversed_at    text,
  rev            bigint not null default nextval('cf.rev_seq')
);
create index if not exists ix_payments_receivable on cf.payments(receivable_id);

create table if not exists cf.audit_log (
  id        bigint generated by default as identity primary key,
  ts        text not null,
  entity    text not null,
  entity_id bigint,
  action    text not null,
  summary   text not null,
  details   text,
  rev       bigint not null default nextval('cf.rev_seq')
);

-- "rev" muda a cada gravação: é assim que PC e celular sabem que algo mudou (tempo real)
create or replace function cf.touch_rev() returns trigger language plpgsql as $$
begin
  new.rev := nextval('cf.rev_seq');
  return new;
end $$;

do $$
declare t text;
begin
  foreach t in array array['settings','clients','categories','batches','services','receivables','payments','audit_log'] loop
    execute format('drop trigger if exists trg_rev on cf.%I', t);
    execute format('create trigger trg_rev before update on cf.%I for each row execute function cf.touch_rev()', t);
    execute format('alter table cf.%I enable row level security', t);
  end loop;
  alter table cf.secrets enable row level security;
end $$;

-- ------------------------------------------------------------------ utilidades
create or replace function cf.fail(msg text) returns void language plpgsql as $$
begin
  raise exception using errcode = 'P0001', message = msg;
end $$;

create or replace function cf.now_txt() returns text language sql stable as $$
  select to_char(now() at time zone 'America/Santiago', 'YYYY-MM-DD"T"HH24:MI:SS')
$$;

create or replace function cf.today() returns date language sql stable as $$
  select (now() at time zone 'America/Santiago')::date
$$;

create or replace function cf.clean(t text) returns text language sql immutable as $$
  select nullif(regexp_replace(btrim(coalesce(t, '')), '\s+', ' ', 'g'), '')
$$;

create or replace function cf.name_key(t text) returns text language sql stable as $$
  select regexp_replace(lower(extensions.unaccent(btrim(t))), '\s+', ' ', 'g')
$$;

create or replace function cf.fmt(n bigint) returns text language sql immutable as $$
  select case when n < 0 then '-' else '' end || 'CLP ' ||
         replace(to_char(abs(n), 'FM999,999,999,999,990'), ',', '.')
$$;

create or replace function cf.ref(kind text, id bigint) returns text language sql immutable as $$
  select case kind when 'fornada' then 'F' when 'limpeza' then 'L' when 'outro' then 'S'
                   when 'receber' then 'R' when 'manual' then 'R' when 'pagamento' then 'P' else '#' end
         || '-' || lpad(id::text, 5, '0')
$$;

create or replace function cf.br(d date) returns text language sql immutable as $$
  select to_char(d, 'DD/MM/YYYY')
$$;

create or replace function cf.pct(num numeric, den numeric) returns numeric language sql immutable as $$
  select case when coalesce(den, 0) = 0 then null else round(num::numeric * 100 / den, 2) end
$$;

-- valores monetários/quantidades vindos do JSON (aceita número ou texto "CLP 25.000")
create or replace function cf.amt(d jsonb, k text, dflt bigint default 0) returns bigint language plpgsql as $$
declare v jsonb := d -> k; s text; n bigint;
begin
  if v is null or v = 'null'::jsonb or v = '""'::jsonb then return dflt; end if;
  if jsonb_typeof(v) = 'number' then
    if (v #>> '{}')::numeric <> trunc((v #>> '{}')::numeric) then perform cf.fail('Valores em CLP não podem ter centavos.'); end if;
    n := (v #>> '{}')::numeric::bigint;
  else
    s := regexp_replace(upper(v #>> '{}'), '(CLP|\$|\s|\.)', '', 'g');
    if s = '' then return dflt; end if;
    if s !~ '^-?[0-9]+$' then perform cf.fail('Valor inválido: ' || (v #>> '{}')); end if;
    n := s::bigint;
  end if;
  if n < 0 then perform cf.fail('Valores não podem ser negativos.'); end if;
  if n > 2000000000 then perform cf.fail('Valor excede o limite permitido.'); end if;
  return n;
end $$;

create or replace function cf.dt(d jsonb, k text) returns date language plpgsql as $$
begin
  if coalesce(d ->> k, '') = '' then return null; end if;
  return (d ->> k)::date;
exception when others then
  perform cf.fail('Data inválida.');
  return null;
end $$;

create or replace function cf.audit(p_entity text, p_id bigint, p_action text, p_summary text, p_details jsonb default null)
returns void language sql as $$
  insert into cf.audit_log (ts, entity, entity_id, action, summary, details)
  values (cf.now_txt(), p_entity, p_id, p_action, p_summary, p_details::text)
$$;

create or replace function cf.client_id(p_name text, p_contact text default null) returns bigint language plpgsql as $$
declare n text := cf.clean(p_name); k text; cid bigint; cur_contact text;
begin
  if n is null then return null; end if;
  if length(n) > 120 then perform cf.fail('O nome do cliente é muito longo.'); end if;
  k := cf.name_key(n);
  select id, contact into cid, cur_contact from cf.clients where name_key = k;
  if cid is not null then
    if cf.clean(p_contact) is not null and cur_contact is null then
      update cf.clients set contact = cf.clean(p_contact) where id = cid;
    end if;
    return cid;
  end if;
  insert into cf.clients (name, name_key, contact, created_at) values (n, k, cf.clean(p_contact), cf.now_txt())
  returning id into cid;
  return cid;
end $$;

create or replace function cf.setting(k text, dflt text) returns text language sql stable as $$
  select coalesce((select value from cf.settings where key = k), dflt)
$$;

-- ------------------------------------------------------------------ contas a receber
create or replace function cf.rec_paid(p_id bigint) returns bigint language sql stable as $$
  select coalesce(sum(amount), 0)::bigint from cf.payments where receivable_id = p_id and status = 'ativo'
$$;

create or replace function cf.rec_status(p_amount bigint, p_paid bigint, p_due date, p_cancelled boolean)
returns text language sql stable as $$
  select case
    when p_cancelled then 'Cancelado'
    when p_amount - p_paid <= 0 then 'Pago'
    when p_due is not null and p_due < cf.today() then 'Vencido'
    when p_paid > 0 then 'Parcialmente pago'
    else 'Pendente' end
$$;

create or replace function cf.cancel_rec_row(p_id bigint, p_reason text) returns void language plpgsql as $$
declare r record;
begin
  select * into r from cf.receivables where id = p_id;
  update cf.receivables set status = 'cancelado', cancel_reason = p_reason, cancelled_at = cf.now_txt(),
         updated_at = cf.now_txt() where id = p_id;
  perform cf.audit('receber', p_id, 'cancelar', 'Lançamento ' || cf.ref('receber', p_id) || ' cancelado — ' || p_reason,
                   jsonb_build_object('valor', r.amount, 'pago', cf.rec_paid(p_id), 'motivo', p_reason));
end $$;

-- mantém UMA dívida vinculada ao registro de origem, com o valor pendente correto
create or replace function cf.sync_origin(p_type text, p_id bigint, p_pending bigint, p_client text, p_issue date,
                                          p_due date, p_desc text, p_contact text) returns bigint language plpgsql as $$
declare ex record; ex_paid bigint; cid bigint; rid bigint;
begin
  select * into ex from cf.receivables where origin_type = p_type and origin_id = p_id and status = 'aberto';
  ex_paid := case when ex.id is null then 0 else cf.rec_paid(ex.id) end;
  if p_pending > 0 then
    if cf.clean(p_client) is null then perform cf.fail('Informe o nome do cliente para lançar o valor a receber.'); end if;
    if p_due is not null and p_due < p_issue then
      perform cf.fail('A data prevista de recebimento não pode ser anterior à data do registro.');
    end if;
    cid := cf.client_id(p_client, p_contact);
    if ex.id is not null then
      if p_pending < ex_paid then
        perform cf.fail('Já foram registrados pagamentos de ' || cf.fmt(ex_paid) ||
                        ' para este valor a receber. O valor pendente não pode ficar abaixo disso.');
      end if;
      update cf.receivables set client_id = cid, description = p_desc, amount = p_pending, issue_date = p_issue,
             due_date = p_due, contact = coalesce(cf.clean(p_contact), contact), updated_at = cf.now_txt()
       where id = ex.id;
      if ex.amount <> p_pending then
        perform cf.audit('receber', ex.id, 'editar', 'Valor a receber ' || cf.ref('receber', ex.id) || ' ajustado: '
                         || cf.fmt(ex.amount) || ' → ' || cf.fmt(p_pending));
      end if;
      return ex.id;
    end if;
    insert into cf.receivables (client_id, description, amount, issue_date, due_date, contact, origin_type, origin_id,
                                status, created_at, updated_at)
    values (cid, p_desc, p_pending, p_issue, p_due, cf.clean(p_contact), p_type, p_id, 'aberto', cf.now_txt(), cf.now_txt())
    returning id into rid;
    perform cf.audit('receber', rid, 'criar', 'Novo valor a receber ' || cf.ref('receber', rid) || ' — ' || cf.clean(p_client)
                     || ': ' || cf.fmt(p_pending) || ' (origem ' || cf.ref(p_type, p_id) || ')');
    return rid;
  end if;
  if ex.id is not null then
    if ex_paid > 0 then
      perform cf.fail('Já foram registrados pagamentos de ' || cf.fmt(ex_paid) || ' para este valor a receber. '
                      || 'Mantenha a opção ''a receber'' ou estorne os pagamentos antes.');
    end if;
    perform cf.cancel_rec_row(ex.id, 'Registro de origem corrigido: não há mais valor a receber');
  end if;
  return null;
end $$;

create or replace function cf.cancel_for_origin(p_type text, p_id bigint, p_reason text) returns void language plpgsql as $$
declare rid bigint;
begin
  select id into rid from cf.receivables where origin_type = p_type and origin_id = p_id and status = 'aberto';
  if rid is not null then perform cf.cancel_rec_row(rid, p_reason); end if;
end $$;

-- ------------------------------------------------------------------ fornadas
create or replace function cf.batch_save(p_id bigint, d jsonb) returns bigint language plpgsql as $$
declare
  v_date date := coalesce(cf.dt(d, 'date'), cf.today());
  produced bigint := cf.amt(d, 'qty_produced');
  sold bigint := cf.amt(d, 'qty_sold');
  price bigint := cf.amt(d, 'unit_price', cf.setting('salgado_price', '500')::bigint);
  cost bigint := cf.amt(d, 'unit_cost', cf.setting('salgado_cost', '250')::bigint);
  extra bigint := cf.amt(d, 'extra_expenses');
  full_rec boolean := coalesce((d ->> 'fully_received')::boolean, true);
  v_revenue bigint; v_total bigint; upfront bigint; pending bigint; cid bigint; bid bigint; old record;
  descr text;
begin
  if produced = 0 then perform cf.fail('Informe a quantidade produzida (maior que zero).'); end if;
  if sold > produced then perform cf.fail('A quantidade vendida não pode ser maior que a quantidade produzida.'); end if;
  v_revenue := sold * price;
  v_total := produced * cost + extra;
  if v_revenue > 2000000000 or v_total > 2000000000 then perform cf.fail('Os valores da fornada excedem o limite permitido.'); end if;
  upfront := case when full_rec then v_revenue else cf.amt(d, 'paid_upfront') end;
  if upfront > v_revenue then perform cf.fail('O valor recebido no ato não pode ser maior que o faturamento.'); end if;
  pending := v_revenue - upfront;
  if not full_rec and pending = 0 and v_revenue > 0 then
    perform cf.fail('O valor recebido no ato cobre todo o faturamento. Marque ''Recebido integralmente''.');
  end if;
  if length(coalesce(d ->> 'notes', '')) > 2000 then perform cf.fail('As observações são muito longas.'); end if;
  cid := cf.client_id(d ->> 'client_name', d ->> 'contact');
  if p_id is null then
    insert into cf.batches (date, qty_produced, qty_sold, unit_price, unit_cost, extra_expenses, revenue, total_cost, profit,
                            paid_upfront, payment_method, client_id, notes, status, created_at, updated_at)
    values (v_date, produced, sold, price, cost, extra, v_revenue, v_total, v_revenue - v_total, upfront,
            cf.clean(d ->> 'payment_method'), cid, cf.clean(d ->> 'notes'), 'ativo', cf.now_txt(), cf.now_txt())
    returning id into bid;
    perform cf.audit('fornada', bid, 'criar', 'Nova fornada ' || cf.ref('fornada', bid) || ' — ' || sold || '/' || produced
                     || ' vendidos, faturamento ' || cf.fmt(v_revenue));
  else
    select * into old from cf.batches where id = p_id for update;
    if old.id is null then perform cf.fail('Fornada não encontrada.'); end if;
    if old.status = 'cancelado' then perform cf.fail('Não é possível editar uma fornada cancelada.'); end if;
    bid := p_id;
    update cf.batches set date = v_date, qty_produced = produced, qty_sold = sold, unit_price = price, unit_cost = cost,
           extra_expenses = extra, revenue = v_revenue, total_cost = v_total, profit = v_revenue - v_total,
           paid_upfront = upfront, payment_method = cf.clean(d ->> 'payment_method'), client_id = cid,
           notes = cf.clean(d ->> 'notes'), updated_at = cf.now_txt()
     where id = bid;
  end if;
  descr := 'Fornada ' || cf.ref('fornada', bid) || ' de ' || cf.br(v_date) || ' — ' || sold || ' salgado(s)';
  perform cf.sync_origin('fornada', bid, pending, d ->> 'client_name', v_date, cf.dt(d, 'due_date'), descr, d ->> 'contact');
  if p_id is not null then
    perform cf.audit('fornada', bid, 'editar', 'Fornada ' || cf.ref('fornada', bid) || ' corrigida',
      jsonb_build_object('antes', jsonb_build_object('data', old.date, 'produzidos', old.qty_produced, 'vendidos', old.qty_sold,
                                                     'preco', old.unit_price, 'custo', old.unit_cost, 'faturamento', old.revenue),
                         'depois', jsonb_build_object('data', v_date, 'produzidos', produced, 'vendidos', sold,
                                                      'preco', price, 'custo', cost, 'faturamento', v_revenue)));
  end if;
  return bid;
end $$;

create or replace function cf.batch_cancel(p_id bigint, p_reason text) returns void language plpgsql as $$
declare old record; reason text := cf.clean(p_reason);
begin
  select * into old from cf.batches where id = p_id for update;
  if old.id is null then perform cf.fail('Fornada não encontrada.'); end if;
  if old.status = 'cancelado' then perform cf.fail('Esta fornada já está cancelada.'); end if;
  if reason is null then perform cf.fail('Informe o motivo do cancelamento.'); end if;
  update cf.batches set status = 'cancelado', cancel_reason = reason, cancelled_at = cf.now_txt(), updated_at = cf.now_txt()
   where id = p_id;
  perform cf.cancel_for_origin('fornada', p_id, 'Fornada ' || cf.ref('fornada', p_id) || ' cancelada: ' || reason);
  perform cf.audit('fornada', p_id, 'cancelar', 'Fornada ' || cf.ref('fornada', p_id) || ' cancelada — ' || reason,
                   jsonb_build_object('faturamento', old.revenue));
end $$;

-- ------------------------------------------------------------------ serviços
create or replace function cf.job_save(p_id bigint, d jsonb) returns bigint language plpgsql as $$
declare
  v_kind text := coalesce(d ->> 'kind', 'limpeza');
  v_date date := coalesce(cf.dt(d, 'date'), cf.today());
  v_title text := cf.clean(d ->> 'title');
  v_amount bigint := cf.amt(d, 'amount');
  v_costs bigint := cf.amt(d, 'costs');
  v_extra bigint := cf.amt(d, 'extra_expenses');
  full_rec boolean := coalesce((d ->> 'fully_received')::boolean, true);
  label text; upfront bigint; pending bigint; cid bigint; cat bigint; jid bigint; old record; total bigint;
begin
  if v_kind not in ('limpeza', 'outro') then perform cf.fail('Tipo de serviço inválido.'); end if;
  label := case v_kind when 'limpeza' then 'Serviço de limpeza' else 'Outro serviço' end;
  if v_title is null then
    perform cf.fail(case v_kind when 'limpeza' then 'Informe a descrição do serviço.'
                                else 'Informe o nome ou a descrição do trabalho.' end);
  end if;
  total := v_costs + v_extra;
  upfront := case when full_rec then v_amount else cf.amt(d, 'paid_upfront') end;
  if upfront > v_amount then perform cf.fail('O valor recebido no ato não pode ser maior que o faturamento.'); end if;
  pending := v_amount - upfront;
  if not full_rec and pending = 0 and v_amount > 0 then
    perform cf.fail('O valor recebido no ato cobre todo o valor cobrado. Marque ''Recebido integralmente''.');
  end if;
  if v_kind = 'outro' and coalesce(d ->> 'category_id', '') not in ('', 'null') then
    cat := (d ->> 'category_id')::bigint;
    if not exists (select 1 from cf.categories where id = cat) then perform cf.fail('Categoria inválida.'); end if;
  end if;
  cid := cf.client_id(d ->> 'client_name', d ->> 'contact');
  if p_id is null then
    insert into cf.services (kind, date, title, description, client_id, address, category_id, amount, costs, extra_expenses,
                             cost_description, profit, paid_upfront, payment_method, notes, status, created_at, updated_at)
    values (v_kind, v_date, v_title, cf.clean(d ->> 'description'), cid, cf.clean(d ->> 'address'), cat, v_amount, v_costs,
            v_extra, cf.clean(d ->> 'cost_description'), v_amount - total, upfront, cf.clean(d ->> 'payment_method'),
            cf.clean(d ->> 'notes'), 'ativo', cf.now_txt(), cf.now_txt())
    returning id into jid;
    perform cf.audit(v_kind, jid, 'criar', 'Novo ' || lower(label) || ' ' || cf.ref(v_kind, jid) || ' — ' || v_title
                     || ': ' || cf.fmt(v_amount));
  else
    select * into old from cf.services where id = p_id for update;
    if old.id is null or old.kind <> v_kind then perform cf.fail('Serviço não encontrado.'); end if;
    if old.status = 'cancelado' then perform cf.fail('Não é possível editar um serviço cancelado.'); end if;
    jid := p_id;
    update cf.services set date = v_date, title = v_title, description = cf.clean(d ->> 'description'), client_id = cid,
           address = cf.clean(d ->> 'address'), category_id = cat, amount = v_amount, costs = v_costs, extra_expenses = v_extra,
           cost_description = cf.clean(d ->> 'cost_description'), profit = v_amount - total, paid_upfront = upfront,
           payment_method = cf.clean(d ->> 'payment_method'), notes = cf.clean(d ->> 'notes'), updated_at = cf.now_txt()
     where id = jid;
  end if;
  perform cf.sync_origin(v_kind, jid, pending, d ->> 'client_name', v_date, cf.dt(d, 'due_date'),
                         label || ' ' || cf.ref(v_kind, jid) || ' de ' || cf.br(v_date) || ' — ' || v_title, d ->> 'contact');
  if p_id is not null then
    perform cf.audit(v_kind, jid, 'editar', label || ' ' || cf.ref(v_kind, jid) || ' corrigido',
      jsonb_build_object('antes', jsonb_build_object('data', old.date, 'valor', old.amount, 'custos', old.costs + old.extra_expenses),
                         'depois', jsonb_build_object('data', v_date, 'valor', v_amount, 'custos', total)));
  end if;
  return jid;
end $$;

create or replace function cf.job_cancel(p_id bigint, p_reason text) returns void language plpgsql as $$
declare old record; reason text := cf.clean(p_reason); label text;
begin
  select * into old from cf.services where id = p_id for update;
  if old.id is null then perform cf.fail('Serviço não encontrado.'); end if;
  if old.status = 'cancelado' then perform cf.fail('Este serviço já está cancelado.'); end if;
  if reason is null then perform cf.fail('Informe o motivo do cancelamento.'); end if;
  label := case old.kind when 'limpeza' then 'Serviço de limpeza' else 'Outro serviço' end;
  update cf.services set status = 'cancelado', cancel_reason = reason, cancelled_at = cf.now_txt(), updated_at = cf.now_txt()
   where id = p_id;
  perform cf.cancel_for_origin(old.kind, p_id, label || ' ' || cf.ref(old.kind, p_id) || ' cancelado: ' || reason);
  perform cf.audit(old.kind, p_id, 'cancelar', label || ' ' || cf.ref(old.kind, p_id) || ' cancelado — ' || reason,
                   jsonb_build_object('valor', old.amount));
end $$;

-- ------------------------------------------------------------------ lançamentos e pagamentos
create or replace function cf.rec_validate(p_client text, p_desc text, p_amount bigint, p_issue date, p_due date)
returns void language plpgsql as $$
begin
  if cf.clean(p_client) is null then perform cf.fail('Informe o nome do devedor ou cliente.'); end if;
  if cf.clean(p_desc) is null then perform cf.fail('Informe a descrição da origem da dívida.'); end if;
  if p_amount <= 0 then perform cf.fail('O valor devido deve ser maior que zero.'); end if;
  if p_issue is null then perform cf.fail('Informe a data do lançamento.'); end if;
  if p_due is not null and p_due < p_issue then
    perform cf.fail('A data prevista de pagamento não pode ser anterior à data do lançamento.');
  end if;
end $$;

create or replace function cf.rec_create(d jsonb) returns bigint language plpgsql as $$
declare v_amount bigint := cf.amt(d, 'amount'); v_issue date := coalesce(cf.dt(d, 'issue_date'), cf.today());
        v_due date := cf.dt(d, 'due_date'); cid bigint; rid bigint;
begin
  perform cf.rec_validate(d ->> 'client_name', d ->> 'description', v_amount, v_issue, v_due);
  cid := cf.client_id(d ->> 'client_name', d ->> 'contact');
  insert into cf.receivables (client_id, description, amount, issue_date, due_date, contact, origin_type, origin_id, notes,
                              status, created_at, updated_at)
  values (cid, cf.clean(d ->> 'description'), v_amount, v_issue, v_due, cf.clean(d ->> 'contact'), 'manual', null,
          cf.clean(d ->> 'notes'), 'aberto', cf.now_txt(), cf.now_txt())
  returning id into rid;
  perform cf.audit('receber', rid, 'criar', 'Novo valor a receber ' || cf.ref('receber', rid) || ' — '
                   || cf.clean(d ->> 'client_name') || ': ' || cf.fmt(v_amount));
  return rid;
end $$;

create or replace function cf.rec_update(p_id bigint, d jsonb) returns void language plpgsql as $$
declare r record; paid bigint; v_amount bigint; v_issue date; v_due date := cf.dt(d, 'due_date'); cid bigint;
begin
  select * into r from cf.receivables where id = p_id for update;
  if r.id is null then perform cf.fail('Lançamento não encontrado.'); end if;
  if r.status = 'cancelado' then perform cf.fail('Não é possível editar um lançamento cancelado.'); end if;
  if r.origin_type <> 'manual' then v_amount := r.amount; v_issue := r.issue_date;
  else v_amount := cf.amt(d, 'amount'); v_issue := coalesce(cf.dt(d, 'issue_date'), r.issue_date); end if;
  perform cf.rec_validate(d ->> 'client_name', d ->> 'description', v_amount, v_issue, v_due);
  paid := cf.rec_paid(p_id);
  if v_amount < paid then
    perform cf.fail('O valor devido não pode ser menor que o total já pago (' || cf.fmt(paid) || '). '
                    || 'Estorne pagamentos primeiro, se necessário.');
  end if;
  cid := cf.client_id(d ->> 'client_name', d ->> 'contact');
  update cf.receivables set client_id = cid, description = cf.clean(d ->> 'description'), amount = v_amount,
         issue_date = v_issue, due_date = v_due, contact = cf.clean(d ->> 'contact'), notes = cf.clean(d ->> 'notes'),
         updated_at = cf.now_txt() where id = p_id;
  perform cf.audit('receber', p_id, 'editar', 'Lançamento ' || cf.ref('receber', p_id) || ' corrigido',
    jsonb_build_object('antes', jsonb_build_object('valor', r.amount, 'vencimento', r.due_date),
                       'depois', jsonb_build_object('valor', v_amount, 'vencimento', v_due)));
end $$;

create or replace function cf.rec_cancel(p_id bigint, p_reason text) returns void language plpgsql as $$
declare r record; reason text := cf.clean(p_reason);
begin
  select * into r from cf.receivables where id = p_id for update;
  if r.id is null then perform cf.fail('Lançamento não encontrado.'); end if;
  if r.status = 'cancelado' then perform cf.fail('Este lançamento já está cancelado.'); end if;
  if r.origin_type <> 'manual' then
    perform cf.fail('Esta dívida está vinculada ao registro ' || cf.ref(r.origin_type, r.origin_id)
                    || '. Para cancelá-la, edite ou cancele o registro de origem.');
  end if;
  if reason is null then perform cf.fail('Informe o motivo do cancelamento.'); end if;
  perform cf.cancel_rec_row(p_id, reason);
end $$;

create or replace function cf.pay_add(p_id bigint, d jsonb) returns bigint language plpgsql as $$
declare r record; v_amount bigint := cf.amt(d, 'amount'); v_date date := coalesce(cf.dt(d, 'date'), cf.today());
        bal bigint; pid bigint; cname text;
begin
  select * into r from cf.receivables where id = p_id for update;
  if r.id is null then perform cf.fail('Lançamento não encontrado.'); end if;
  if r.status = 'cancelado' then perform cf.fail('Não é possível registrar pagamento em um lançamento cancelado.'); end if;
  if v_amount <= 0 then perform cf.fail('O valor recebido deve ser maior que zero.'); end if;
  bal := r.amount - cf.rec_paid(p_id);
  if bal <= 0 then perform cf.fail('Esta dívida já está totalmente paga.'); end if;
  if v_amount > bal then
    perform cf.fail('O valor informado (' || cf.fmt(v_amount) || ') é maior que o saldo pendente (' || cf.fmt(bal)
                    || '). Registre no máximo o saldo; valores excedentes não são aceitos.');
  end if;
  if v_date < r.issue_date then perform cf.fail('A data do recebimento não pode ser anterior à data do lançamento.'); end if;
  insert into cf.payments (receivable_id, amount, date, method, notes, status, created_at)
  values (p_id, v_amount, v_date, cf.clean(d ->> 'method'), cf.clean(d ->> 'notes'), 'ativo', cf.now_txt())
  returning id into pid;
  select name into cname from cf.clients where id = r.client_id;
  perform cf.audit('pagamento', pid, 'criar', 'Pagamento confirmado — ' || cname || ': ' || cf.fmt(v_amount) || ' ('
                   || cf.ref('receber', p_id) || ', ' || case when bal - v_amount = 0 then 'quitado'
                                                              else 'saldo ' || cf.fmt(bal - v_amount) end || ')',
                   jsonb_build_object('receber', p_id, 'valor', v_amount, 'saldo_restante', bal - v_amount));
  return pid;
end $$;

create or replace function cf.pay_reverse(p_id bigint, p_reason text) returns void language plpgsql as $$
declare p record; reason text := cf.clean(p_reason);
begin
  select * into p from cf.payments where id = p_id for update;
  if p.id is null then perform cf.fail('Pagamento não encontrado.'); end if;
  if p.status <> 'ativo' then perform cf.fail('Este pagamento já foi estornado.'); end if;
  if reason is null then perform cf.fail('Informe o motivo do estorno.'); end if;
  update cf.payments set status = 'estornado', reverse_reason = reason, reversed_at = cf.now_txt() where id = p_id;
  perform cf.audit('pagamento', p_id, 'estornar', 'Pagamento ' || cf.ref('pagamento', p_id) || ' estornado: '
                   || cf.fmt(p.amount) || ' — ' || reason, jsonb_build_object('receber', p.receivable_id, 'valor', p.amount));
end $$;

-- ------------------------------------------------------------------ categorias e configurações
create or replace function cf.cat_save(d jsonb) returns bigint language plpgsql as $$
declare n text := cf.clean(d ->> 'name'); k text; r record; cid bigint := nullif(d ->> 'id', '')::bigint; old text;
begin
  if d ? 'active' and cid is not null then
    select * into r from cf.categories where id = cid;
    if r.id is null then perform cf.fail('Categoria não encontrada.'); end if;
    update cf.categories set active = case when (d ->> 'active')::boolean then 1 else 0 end where id = cid;
    perform cf.audit('categoria', cid, case when (d ->> 'active')::boolean then 'reativar' else 'desativar' end,
                     'Categoria ' || case when (d ->> 'active')::boolean then 'reativada' else 'desativada' end || ': ' || r.name);
    return cid;
  end if;
  if n is null then perform cf.fail('Informe o nome da categoria.'); end if;
  k := cf.name_key(n);
  if cid is not null then
    if exists (select 1 from cf.categories where name_key = k and id <> cid) then
      perform cf.fail('Já existe uma categoria com esse nome.');
    end if;
    select name into old from cf.categories where id = cid;
    update cf.categories set name = n, name_key = k where id = cid;
    perform cf.audit('categoria', cid, 'editar', 'Categoria renomeada: ' || old || ' → ' || n);
    return cid;
  end if;
  select * into r from cf.categories where name_key = k;
  if r.id is not null then
    if r.active = 1 then perform cf.fail('Já existe uma categoria com esse nome.'); end if;
    update cf.categories set active = 1, name = n where id = r.id;
    perform cf.audit('categoria', r.id, 'reativar', 'Categoria reativada: ' || n);
    return r.id;
  end if;
  insert into cf.categories (name, name_key, active, created_at) values (n, k, 1, cf.now_txt()) returning id into cid;
  perform cf.audit('categoria', cid, 'criar', 'Nova categoria: ' || n);
  return cid;
end $$;

-- apenas as configurações comuns a todos os aparelhos ficam na nuvem
create or replace function cf.settings_save(d jsonb) returns void language plpgsql as $$
declare k text; v text; old text; changes text := '';
begin
  for k, v in select * from jsonb_each_text(d) loop
    if k not in ('app_display_name', 'salgado_price', 'salgado_margin', 'salgado_cost', 'limpeza_default_cost') then
      continue;
    end if;
    if k in ('salgado_price', 'salgado_cost', 'limpeza_default_cost') and v !~ '^[0-9]+$' then
      perform cf.fail('Informe um valor inteiro em CLP.');
    end if;
    select value into old from cf.settings where key = k;
    if old is distinct from v then
      insert into cf.settings (key, value, updated_at) values (k, v, cf.now_txt())
        on conflict (key) do update set value = excluded.value, updated_at = excluded.updated_at;
      changes := changes || case when changes = '' then '' else ', ' end || k || ': ' || coalesce(old, '—') || ' → ' || v;
    end if;
  end loop;
  if changes <> '' then perform cf.audit('configuracao', null, 'editar', 'Configurações alteradas — ' || changes); end if;
end $$;

