-- situação de recebimento de um registro de origem (fornada/serviço)
create or replace function cf.origin_json(p_type text, p_id bigint, p_status text, p_value bigint, p_upfront bigint)
returns jsonb language plpgsql stable as $$
declare r cf.v_receivables; st text;
begin
  select * into r from cf.v_receivables where origin_type = p_type and origin_id = p_id
   order by (status = 'aberto') desc, id desc limit 1;
  if p_status = 'cancelado' then st := 'Cancelado';
  elsif r.id is not null and r.status = 'aberto' then st := cf.rec_status(r.amount, r.paid, r.due_date, false);
  elsif p_value > 0 then st := 'Recebido';
  else st := case p_type when 'fornada' then 'Sem venda' else 'Sem valor' end;
  end if;
  if st = 'Pago' then st := 'Recebido'; end if;
  return jsonb_build_object(
    'pay_status', st,
    'received', p_upfront + case when r.status = 'aberto' then r.paid else 0 end,
    'to_receive', case when r.status = 'aberto' then greatest(r.amount - r.paid, 0) else 0 end,
    'receivable_id', r.id, 'due_date', r.due_date);
end $$;

